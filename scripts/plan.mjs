// docs/plan/K<n>.md (one file per plan row) + docs/plan/_template.md -> docs/PLAN.md.
//   node scripts/plan.mjs          write docs/PLAN.md
//   node scripts/plan.mjs --check  fail when it is stale
// Row file: front matter (`section`, `order`, then one key per extra table column, lowercase, spaces as '-'), then the content line.
// Template: PLAN.md with `<!-- rows: <heading> -->` where a table's K rows go; the header line above says the columns.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

export const key = (h) => h.trim().toLowerCase().replace(/\s+/g, '-')
export function loadRows(top) {
  const dir = path.join(top, 'docs', 'plan')
  const rows = fs.readdirSync(dir).filter((f) => f.endsWith('.md') && !f.startsWith('_')).map((f) => {
    const t = fs.readFileSync(path.join(dir, f), 'utf8').replace(/\r\n/g, '\n')
    const m = t.match(/^---\n([\s\S]*?)\n---\n([\s\S]*?)\n?$/)
    if (!m) throw new Error('docs/plan/' + f + ': no front matter (--- ... --- then the content line)')
    const r = { file: f, id: f.replace(/(-\d+)?\.md$/, ''), content: m[2].trim() }
    for (const l of m[1].split('\n')) { const i = l.indexOf(':'); r[l.slice(0, i)] = l.slice(i + 1).trim() }
    r.n = Number(r.id.replace(/\D/g, '') || 0)
    return r
  })
  const rank = {}
  for (const r of rows) if (r.order) rank[r.section] = Math.min(rank[r.section] ?? Infinity, Number(r.order))
  const k = (r) => [rank[r.section] ?? Infinity, r.order ? Number(r.order) : Infinity, r.n]
  return rows.sort((a, b) => { const p = k(a), q = k(b); return p[0] !== q[0] ? (p[0] < q[0] ? -1 : 1) : p[1] !== q[1] ? (p[1] < q[1] ? -1 : 1) : p[2] !== q[2] ? p[2] - q[2] : a.file.localeCompare(b.file) })
}
export function render(top) {
  const rows = loadRows(top)
  const tpl = fs.readFileSync(path.join(top, 'docs', 'plan', '_template.md'), 'utf8').replace(/\r\n/g, '\n').split('\n')
  const known = new Set(tpl.map((l) => l.match(/^<!-- rows: (.*) -->$/)?.[1]).filter(Boolean))
  const bad = rows.filter((r) => !known.has(r.section))
  if (bad.length) throw new Error(bad.map((r) => 'docs/plan/' + r.file + ': section "' + r.section + '" has no <!-- rows: ... --> line in docs/plan/_template.md').join('\n'))
  // K673: every row carries a state; a row whose content or a column says "(done" or "(covered" is in a done state
  const said = (r) => Object.entries(r).some(([k, v]) => !['state', 'file', 'id', 'n'].includes(k) && /\((?:[^)]*[;,:]\s*)?(done|covered)\b/i.test(String(v)))
  const st = rows.filter((r) => !r.state || (said(r) && !/^(done|covered|closed)\b/i.test(r.state)))
  if (st.length) throw new Error(st.map((r) => 'docs/plan/' + r.file + (r.state ? ': says done but its state is "' + r.state + '": set state: done' : ': no state: line in its front matter (state: done, open, candidate, ...)')).join('\n'))
  return tpl.flatMap((l, i) => {
    const m = l.match(/^<!-- rows: (.*) -->$/)
    if (!m) return [l]
    const cols = tpl[i - 2].replace(/^\||\|$/g, '').split('|').map(key)
    return rows.filter((r) => r.section === m[1]).map((r) => '| ' + [r.id, r.content, ...cols.slice(2).map((c) => r[c] ?? '')].join(' | ') + ' |')
  }).join('\n')
}
export const isCandidate = (r) => /^(candidate|proposed)/i.test(r.state ?? '')
export const wantedBy = (r) => r['wanted-by'] ?? r['asked-by'] ?? ''
export function candidatesPage(top) {
  const e = (t) => t.replace(/\|/g, '\\|').replace(/\n/g, ' ')
  return ['# Candidates', '', 'Generated by `node scripts/plan.mjs` from docs/plan/: parts a game wants and nobody builds yet (`node kit.mjs search <words>` reads this page). A second game is added to "Wanted by", never a second row.', '', '| Id | Content | Wanted by | Tags |', '|---|---|---|---|',
    ...loadRows(top).filter(isCandidate).map((r) => '| ' + [r.id, e(r.content), e(wantedBy(r)), e(r.tags ?? '')].join(' | ') + ' |'), ''].join('\n')
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const top = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
  try {
    const out = [[path.join(top, 'docs', 'PLAN.md'), render(top)], [path.join(top, 'docs', 'recipes', 'candidates.md'), candidatesPage(top)]]
    for (const [f, text] of out) {
      if (!fs.existsSync(path.dirname(f))) continue
      if (process.argv[2] === '--check') {
        if (!fs.existsSync(f) || fs.readFileSync(f, 'utf8').replace(/\r\n/g, '\n') !== text) { console.error(path.relative(top, f).replace(/\\/g, '/') + ' is stale: run node scripts/plan.mjs'); process.exit(1) }
      } else if (fs.existsSync(path.dirname(f))) fs.writeFileSync(f, text)
    }
  } catch (e) { console.error(e.message); process.exit(1) }
}
