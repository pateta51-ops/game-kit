import { fireEvent, render, screen } from '@testing-library/react'
import { describe, expect, it, vi } from 'vitest'
import { Pile } from './ui.ts'

const face = (id: string, i: { mark?: string; why?: string }) => <b data-face={id} data-fmark={i.mark}>{id}</b>
const back = () => <i />
const cards = ['a', 'b', 'c']
const base = { label: 'Discard', face, back, view: { count: 3, cards }, speed: 0, unit: () => 10 }
const open = () => fireEvent.click(screen.getByRole('button', { name: /Look through|Choose/ }))
const hits = () => [...document.querySelectorAll<HTMLElement>('[data-part="fan-hit"]')]

describe('K254 pile additions', () => {
  it('markOf: mark and why on the card and its title; dim stays selectable, barred is disabled; the face sees the mark', () => {
    const tap = vi.fn()
    render(<Pile {...base} pick={{ marks: { a: 'legal' }, tap }} markOf={(id) => (id === 'b' ? { mark: 'dim', why: 'costs 2' } : id === 'c' ? { mark: 'barred', why: 'no' } : undefined)} />)
    open()
    const h = hits()
    expect(h[1]!.dataset.mark).toBe('dim')
    expect(h[1]!.dataset.why).toBe('costs 2')
    expect(h[1]!.title).toBe('costs 2')
    expect((h[2] as HTMLButtonElement).disabled).toBe(true)
    expect((h[1] as HTMLButtonElement).disabled).toBe(false)
    expect(h[1]!.querySelector('[data-fmark]')!.getAttribute('data-fmark')).toBe('dim')
    fireEvent.click(h[1]!)
    fireEvent.click(h[2]!)
    expect(tap.mock.calls).toEqual([['b']])
  })
  it('onTap replaces pick.tap with via and detail; a double-click second click is dropped', () => {
    const tap = vi.fn()
    const onTap = vi.fn()
    render(<Pile {...base} pick={{ marks: { a: 'legal' }, tap }} onTap={onTap} />)
    open()
    fireEvent.click(hits()[0]!, { detail: 1 })
    fireEvent.click(hits()[0]!, { detail: 2 })
    fireEvent.click(hits()[0]!, { detail: 0 })
    expect(onTap.mock.calls).toEqual([['a', { via: 'pointer', detail: 1 }], ['a', { via: 'key', detail: 0 }]])
    expect(tap).not.toHaveBeenCalled()
  })
  it('cardProps: the game props reach the fan card and its onClick is composed', () => {
    const own = vi.fn()
    const tap = vi.fn()
    render(<Pile {...base} pick={{ marks: { a: 'legal' }, tap }} cardProps={(id) => ({ 'data-testid': `c-${id}`, className: 'mine', 'aria-pressed': true, onClick: own })} />)
    open()
    const el = screen.getByTestId('c-a')
    expect(el.className).toBe('mine')
    expect(el.dataset.part).toBe('fan-hit')
    fireEvent.click(el)
    expect(own).toHaveBeenCalled()
    expect(tap).toHaveBeenCalledWith('a')
  })
  it('onPreview: hover on the top card, focus on a fanned card, leave gives null', () => {
    const pv = vi.fn()
    render(<Pile {...base} onPreview={pv} />)
    const hit = document.querySelector('[data-part="stack-hit"]')!
    fireEvent.pointerEnter(hit)
    fireEvent.pointerLeave(hit)
    expect(pv.mock.calls.map((c: unknown[]) => c.slice(0, 2))).toEqual([['a', 'top'], [null, 'top']])
    open()
    pv.mockClear()
    fireEvent.focus(hits()[1]!)
    fireEvent.blur(hits()[1]!)
    expect(pv.mock.calls.map((c: unknown[]) => c.slice(0, 2))).toEqual([['b', 'fan'], [null, 'fan']])
  })
  it('badge shows while the prompt names cards; the backdrop leaves a hole for the show panel', () => {
    document.body.insertAdjacentHTML('beforeend', '<div id="panel"></div>')
    const { container } = render(<Pile {...base} pick={{ marks: { a: 'legal', b: 'legal' }, tap: () => undefined }} badge={(n) => `Choose - ${String(n)}`} show="#panel" />)
    expect(container.querySelector('[data-part="pick-badge"]')!.textContent).toBe('Choose - 2')
    open()
    expect(document.querySelector('[data-part="backdrop"]')!.getAttribute('data-holes')).toBe('1')
  })
  it('no badge when nothing is named', () => {
    const { container } = render(<Pile {...base} badge={() => 'x'} />)
    expect(container.querySelector('[data-part="pick-badge"]')).toBeNull()
  })
  it('phone grid: markOf, cardProps and onTap work there too', () => {
    const onTap = vi.fn()
    render(<Pile {...base} phone pick={{ marks: { a: 'legal' }, tap: () => undefined }} onTap={onTap} markOf={(id) => (id === 'a' ? { why: 'why' } : undefined)} cardProps={(id) => ({ 'data-testid': `g-${id}` })} />)
    open()
    fireEvent.click(screen.getByTestId('g-a'))
    expect(onTap).toHaveBeenCalledWith('a', { via: 'key', detail: 0 })
    expect(screen.getByTestId('g-a').title).toBe('why')
  })
  it('the kit attributes win over cardProps; an undefined why keeps the game title', () => {
    render(<Pile {...base} pick={{ marks: { a: 'legal' }, tap: () => undefined }} cardProps={() => ({ title: 'mine', 'data-part': 'x', disabled: true, 'data-testid': 't' })} />)
    open()
    const h = hits()
    expect(h[0]!.dataset.part).toBe('fan-hit')
    expect((h[0] as HTMLButtonElement).disabled).toBe(false)
    expect(h[0]!.title).toBe('mine')
  })
  it('the game onFocus and onBlur are composed with the preview', () => {
    const f = vi.fn()
    const b = vi.fn()
    render(<Pile {...base} onPreview={() => undefined} cardProps={() => ({ onFocus: f, onBlur: b })} />)
    open()
    fireEvent.focus(hits()[0]!)
    fireEvent.blur(hits()[0]!)
    expect(f).toHaveBeenCalled()
    expect(b).toHaveBeenCalled()
  })
  it('a key press in the fan reports via key; a face-down card sends no id', () => {
    const onTap = vi.fn()
    const pv = vi.fn()
    render(<Pile {...base} view={{ count: 2, cards: ['a', null] }} pick={{ marks: { a: 'legal' }, tap: () => undefined }} onTap={onTap} onPreview={pv} />)
    open()
    pv.mockClear()
    fireEvent.click(hits()[0]!, { detail: 0 })
    expect(onTap).toHaveBeenCalledWith('a', { via: 'key', detail: 0 })
    fireEvent.focus(hits()[1]!)
    fireEvent.pointerEnter(hits()[1]!.closest('[data-part="fan-turn"]')!)
    expect(pv).not.toHaveBeenCalled()
  })
  it('grid: onPreview on focus, null when the sheet closes; a double click acts without onTap, is dropped with it', () => {
    const pv = vi.fn()
    const detail = vi.fn()
    const { rerender } = render(<Pile {...base} phone onPreview={pv} onDetail={detail} />)
    open()
    const g = document.querySelector<HTMLElement>('[data-part="grid-card"]')!
    fireEvent.focus(g)
    expect(pv.mock.calls[0]!.slice(0, 2)).toEqual(['a', 'grid'])
    fireEvent.click(g, { detail: 2 })
    expect(detail).toHaveBeenCalledTimes(1)
    rerender(<Pile {...base} phone onPreview={pv} onDetail={detail} onTap={() => undefined} />)
    fireEvent.click(document.querySelector('[data-part="grid-card"]')!, { detail: 2 })
    expect(detail).toHaveBeenCalledTimes(1)
    pv.mockClear()
    open()
    expect(pv.mock.calls.map((c: unknown[]) => c.slice(0, 2))).toContainEqual([null, 'grid'])
  })
})
